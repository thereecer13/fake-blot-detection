"""Ask a Claude model whether each blot image is real or AI-generated.

No automatic fallback to a different model is configured: if the model declines,
the refusal is recorded as a result, so every score comes from the model you chose.
"""

import base64
import json
from pathlib import Path
from typing import Literal

import anthropic
from pydantic import BaseModel, Field, ValidationError

PROMPT_VERSION = "v1"
PROMPT = """\
You are an expert in scientific image integrity. The image below is a western blot. \
Some images in this set are real blots from published papers; others were generated by \
an AI system or by a computer program. All images were converted to grayscale and \
resized the same way, so ignore file format and resolution.

Judge whether this blot is real or AI-generated. Give the probability (0 to 1) that it \
is AI-generated, your verdict, and a short explanation of the visual evidence."""


class Judgment(BaseModel):
    reasoning: str = Field(description="Short explanation of the visual evidence")
    verdict: Literal["real", "ai"]
    probability_ai: float = Field(ge=0, le=1)


JUDGMENT_SCHEMA = {
    "type": "object",
    "properties": {
        "reasoning": {"type": "string"},
        "verdict": {"type": "string", "enum": ["real", "ai"]},
        "probability_ai": {"type": "number"},
    },
    "required": ["reasoning", "verdict", "probability_ai"],
    "additionalProperties": False,
}


class ClaudeDetector:
    def __init__(
        self,
        model: str = "claude-opus-5-5",
        effort: str = "high",
        client: anthropic.Anthropic | None = None,
    ):
        self.model = model
        self.effort = effort
        self.client = client or anthropic.Anthropic()

    @property
    def name(self) -> str:
        return f"{self.model}/{self.effort}/prompt-{PROMPT_VERSION}"

    def judge(self, image_path: Path) -> dict:
        data = base64.standard_b64encode(image_path.read_bytes()).decode()
        response = self.client.messages.create(
            model=self.model,
            max_tokens=16000,
            output_config={
                "effort": self.effort,
                "format": {"type": "json_schema", "schema": JUDGMENT_SCHEMA},
            },
            messages=[
                {
                    "role": "user",
                    "content": [
                        {
                            "type": "image",
                            "source": {"type": "base64", "media_type": "image/jpeg", "data": data},
                        },
                        {"type": "text", "text": PROMPT},
                    ],
                }
            ],
        )
        result = {"stop_reason": response.stop_reason, "model_served": response.model}
        if response.stop_reason == "refusal":
            result["refusal_category"] = getattr(response.stop_details, "category", None)
            return result
        if response.stop_reason != "end_turn":
            return result
        text = "".join(block.text for block in response.content if block.type == "text")
        result.update(Judgment.model_validate_json(text).model_dump())
        return result


def run_detector(detector, manifest: list[dict], data_dir: Path, out_path: Path) -> list[dict]:
    """Judge every image in the manifest, appending one JSON line per image to `out_path`.

    Images already present in `out_path` are skipped, so an interrupted run can resume.
    """
    done = {}
    if out_path.exists():
        for line in out_path.read_text().splitlines():
            rec = json.loads(line)
            done[rec["image_id"]] = rec
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "a") as f:
        for i, row in enumerate(manifest, 1):
            if row["image_id"] in done:
                continue
            try:
                result = detector.judge(data_dir / row["path"])
            except anthropic.APIStatusError as e:
                if e.status_code == 429 or e.status_code >= 500:
                    raise  # transient: stop here; re-running resumes where it left off
                result = {"error": f"{e.status_code}: {e.message}"}
            except ValidationError as e:
                result = {"error": f"unparseable answer: {e}"}
            rec = {"image_id": row["image_id"], "detector": detector.name, **result}
            f.write(json.dumps(rec) + "\n")
            f.flush()
            done[row["image_id"]] = rec
            print(
                f"[{i}/{len(manifest)}] {row['image_id']} -> "
                f"{rec.get('verdict', rec.get('stop_reason'))} {rec.get('probability_ai', '')}"
            )
    return [done[row["image_id"]] for row in manifest if row["image_id"] in done]
